#!/usr/bin/env node
/**
 * Renders every email kit 02 can send, against a fixed sample, into
 * docs/EMAILS.md. A partner can then read the whole thing before installing,
 * and any change to the copy shows up as a readable diff in review.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { KITS_ROOT } from './lib/bundle.js';
import { addDays } from '../kits/uk-accountancy/02-mtd-vat-reminders/src/core/dates.js';
import { plan } from '../kits/uk-accountancy/02-mtd-vat-reminders/src/core/plan.js';
import { buildDigest } from '../kits/uk-accountancy/02-mtd-vat-reminders/src/core/copy.js';
import { vatReturnDeadline } from '../kits/uk-accountancy/02-mtd-vat-reminders/src/core/deadline.js';
import { withDefaults } from '../kits/uk-accountancy/02-mtd-vat-reminders/src/core/config.js';

const KIT = join(KITS_ROOT, '02-mtd-vat-reminders');

const config = {
  dryRun: false,
  firmName: 'Example Accountants Ltd',
  senderName: 'Accounts',
  senderEmail: 'reminders@exampleaccountants.co.uk',
  replyToEmail: 'reminders@exampleaccountants.co.uk',
  firmPhone: '01234 567890',
  signOffName: 'Sam Patel',
  // The sample year is in the far future, so the rules file would look stale.
  vatRules: { ...withDefaults({}).vatRules, validAsOf: '2099-06-01' },
};

// A Tuesday far in the future, so nothing here reads as a real HMRC date.
const today = '2099-06-16';

/**
 * A sample row due `days` after today. Where a period ends on the last day of a month
 * the kit calculates the date itself; otherwise the sheet's HMRC Due Date is used, which
 * is how a practice enters a non-standard period.
 */
function dueIn(days) {
  const target = addDays(today, days);
  for (let back = 0; back < 120; back += 1) {
    const end = addDays(today, -back);
    const r = vatReturnDeadline(end, config.vatRules);
    if (r.ok && r.dueDate === target) return { end, hmrc: '' };
  }
  // No month-end period gives this date: a non-standard period with the date typed in.
  let end = addDays(target, -38);
  if (vatReturnDeadline(end, config.vatRules).ok) end = addDays(end, 1);
  return { end, hmrc: target };
}
const periodEndFor = (days) => dueIn(days).end;
const hmrcFor = (days) => dueIn(days).hmrc;

const row = (n, client, email, end, extra = {}) => ({
  row_number: n, 'Client Name': client, 'Contact Email': email, 'VAT Period End': end,
  Submitted: 'No', 'VAT Scheme': '', 'HMRC Due Date': '', 'Last Checklist Sent': '',
  'Checklist For Period End': '', 'Last Checklist On': '', ...extra,
});

const cases = [
  ['Advance notice, 21 days out',
    'The first checklist. Calm, no pressure, asks the client to work through the list and send what is outstanding.',
    [row(2, 'Borough Cafe Ltd', 'ap@boroughcafe.co.uk', periodEndFor(21), { 'HMRC Due Date': hmrcFor(21) })]],
  ['Reminder, 14 days out',
    'A firmer prompt, only if the client has not already dealt with it.',
    [row(3, 'Castle Motors Ltd', 'ap@castlemotors.co.uk', periodEndFor(14), { 'HMRC Due Date': hmrcFor(14) })]],
  ['Urgent reminder, 7 days out',
    'The deadline is close. Asks for anything outstanding within the next few days.',
    [row(4, 'Delta Design Ltd', 'studio@deltadesign.co.uk', periodEndFor(7), { 'HMRC Due Date': hmrcFor(7) })]],
  ['Final reminder, 3 days out',
    'The last one. Asks the client to make contact today if anything is outstanding.',
    [row(5, 'Jane Example', 'jane@example.com', periodEndFor(3), { 'HMRC Due Date': hmrcFor(3) })]],
  ['A deadline that falls on a weekend',
    'HMRC does not move the VAT deadline for weekends or bank holidays, so the email says so.',
    [row(6, 'Weekend Ltd', 'ap@weekend.co.uk', '2099-09-30')]],
  ['A period that does not end on a month end, with no HMRC Due Date',
    'The kit does not calculate a date for these, so it sends nothing and tells the practice (see the preview below). Type the due date from the client\'s VAT online account into HMRC Due Date to start the reminders.',
    [row(9, 'Odd Period Ltd', 'ap@oddperiod.co.uk', '2099-05-23')]],
  ['A client with two open VAT periods',
    'One email, every period that is due a reminder listed, pitched at the tone the nearest one warrants. The client is not sent two separate emails.',
    [row(7, 'Multi Ltd', 'ap@multi.co.uk', periodEndFor(7), { 'HMRC Due Date': hmrcFor(7) }), row(8, 'Multi Ltd', 'ap@multi.co.uk', periodEndFor(14), { 'HMRC Due Date': hmrcFor(14) })]],
];
// The weekend case is reminded on its own day, not on the shared sample day.
const dayFor = (title) => (title.startsWith('A deadline that falls on a weekend') ? '2099-10-27' : today);

const out = [
  '# Every email this kit can send',
  '',
  '_Generated by `scripts/render-emails-02.js`. Do not edit by hand; change the copy',
  `in \`src/core/copy.js\` and regenerate. Rendered against a sample practice on ${today}._`,
  '',
  'Read this before installing. It is the whole of what a client will ever receive.',
  'The emails remind and ask. They state no penalty, rate or figure, and never say',
  'that anything has been submitted or paid. The kit never submits a VAT return to HMRC.',
  'In these samples a period that ends on the last day of a month has its deadline calculated by the kit; any other period is shown with the due date typed into the HMRC Due Date column, because the kit does not calculate those.',
  '',
];

for (const [title, note, rows] of cases) {
  const r = plan({ rows, today: dayFor(title), config });
  out.push(`## ${title}`, '', note, '');
  if (!r.actions.length) {
    out.push('_No email is sent in this case._', '', ...r.skipped.map((s) => `- ${s.label}: ${s.reason}`), '');
    continue;
  }
  for (const a of r.actions) {
    out.push('```text', `To:      ${a.realRecipient}`, `Subject: ${a.subject}`, '', a.body, '```', '');
  }
}

const all = cases.filter(([t]) => !t.startsWith('A deadline that falls')).flatMap(([, , rows]) => rows)
  .map((r, i) => ({ ...r, row_number: i + 2 }));
all.push(row(all.length + 2, 'Done Ltd', 'ap@done.co.uk', addDays(today, -40), { Submitted: 'Yes' }));
all.push(row(all.length + 2, 'Late Ltd', 'ap@late.co.uk', '2099-03-31'));
const previewPlan = plan({ rows: all, today, config });
const digest = buildDigest({
  actions: previewPlan.actions, skipped: previewPlan.skipped, runDate: today,
  config: withDefaults(config), confirmations: previewPlan.confirmations, notices: previewPlan.notices,
});
out.push('## The 08:30 preview, sent to the practice',
  '', 'Not a client email. This is what the practice sees 30 minutes before anything goes out.', '',
  '```text', `To:      ${config.senderEmail}`, `Subject: ${digest.subject}`, '', digest.body, '```', '');

writeFileSync(join(KIT, 'docs', 'EMAILS.md'), `${out.join('\n')}\n`);
console.log('wrote kits/uk-accountancy/02-mtd-vat-reminders/docs/EMAILS.md');
