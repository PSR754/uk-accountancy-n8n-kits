#!/usr/bin/env node
/**
 * Renders every email kit 01 can send, against a fixed sample, into
 * docs/EMAILS.md. A partner can then read the whole thing before installing,
 * and any change to the copy shows up as a readable diff in review.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { KITS_ROOT } from './lib/bundle.js';
import { addDays } from '../kits/uk-accountancy/01-hmrc-deadline-reminders/src/core/dates.js';
import { plan } from '../kits/uk-accountancy/01-hmrc-deadline-reminders/src/core/plan.js';
import { buildDigest } from '../kits/uk-accountancy/01-hmrc-deadline-reminders/src/core/copy.js';
import { withDefaults } from '../kits/uk-accountancy/01-hmrc-deadline-reminders/src/core/config.js';

const KIT = join(KITS_ROOT, '01-hmrc-deadline-reminders');

const config = {
  dryRun: false,
  firmName: 'Example Accountants Ltd',
  senderName: 'Accounts',
  senderEmail: 'reminders@exampleaccountants.co.uk',
  replyToEmail: 'reminders@exampleaccountants.co.uk',
  firmPhone: '01234 567890',
  signOffName: 'Sam Patel',
};

const row = (n, client, email, type, due, extra = {}) => ({
  row_number: n, 'Client Name': client, 'Deadline Type': type, 'Due Date': due,
  'Contact Email': email, Status: 'Pending', 'Last Reminder Sent': '',
  'Reminded For Due Date': '', 'Last Reminded On': '', ...extra,
});

// A Tuesday far in the future, with clearly fake deadlines set at each
// milestone, so nothing here reads as a real HMRC or Companies House date.
const today = '2099-06-16';
const inDays = (n) => addDays(today, n);
const cases = [
  ['Advance notice, 30 days out',
    'The first reminder. Calm, no pressure, asks the client to start gathering what is needed.',
    [row(2, 'Borough Cafe Ltd', 'ap@boroughcafe.co.uk', 'Example filing', inDays(30))]],
  ['Reminder, 14 days out',
    'A firmer prompt, only if the client has not already dealt with it.',
    [row(3, 'Castle Motors Ltd', 'ap@castlemotors.co.uk', 'Example filing', inDays(14))]],
  ['Urgent reminder, 7 days out',
    'The deadline is close. Asks for anything outstanding within the next few days.',
    [row(4, 'Delta Design Ltd', 'studio@deltadesign.co.uk', 'Example filing', inDays(7))]],
  ['Final reminder, the day before',
    'The last one. Asks the client to make contact today if anything is outstanding.',
    [row(5, 'Jane Example', 'jane@example.com', 'Example filing', inDays(1))]],
  ['A client with several deadlines',
    'One email, every deadline that is due a reminder listed, pitched at the tone the nearest one warrants. The client is not sent three separate emails.',
    [row(6, 'Multi Ltd', 'ap@multi.co.uk', 'Example filing A', inDays(7)),
      row(7, 'Multi Ltd', 'ap@multi.co.uk', 'Example filing B', inDays(20)),
      row(8, 'Multi Ltd', 'ap@multi.co.uk', 'Example filing C', inDays(75))]],
];

const out = [
  '# Every email this kit can send',
  '',
  '_Generated by `scripts/render-emails-01.js`. Do not edit by hand; change the copy',
  `in \`src/core/copy.js\` and regenerate. Rendered against a sample practice on ${today}._`,
  '',
  'Read this before installing. It is the whole of what a client will ever receive.',
  'The emails remind and ask. They state no penalty, rate or figure, and never say',
  'that anything has been filed or paid.',
  '',
];

for (const [title, note, rows] of cases) {
  const r = plan({ rows, today, config });
  out.push(`## ${title}`, '', note, '');
  if (!r.actions.length) {
    out.push('_No email is sent in this case._', '', ...r.skipped.map((s) => `- ${s.label}: ${s.reason}`), '');
    continue;
  }
  for (const a of r.actions) {
    out.push('```text', `To:      ${a.realRecipient}`, `Subject: ${a.subject}`, '', a.body, '```', '');
  }
}

const all = cases.flatMap(([, , rows]) => rows).map((r, i) => ({ ...r, row_number: i + 2 }));
const previewPlan = plan({ rows: all, today, config });
const digest = buildDigest({
  actions: previewPlan.actions, skipped: previewPlan.skipped, runDate: today,
  config: withDefaults(config),
});
out.push('## The 08:30 preview, sent to the practice',
  '', 'Not a client email. This is what the practice sees 30 minutes before anything goes out.', '',
  '```text', `To:      ${config.senderEmail}`, `Subject: ${digest.subject}`, '', digest.body, '```', '');

writeFileSync(join(KIT, 'docs', 'EMAILS.md'), `${out.join('\n')}\n`);
console.log('wrote kits/uk-accountancy/01-hmrc-deadline-reminders/docs/EMAILS.md');
